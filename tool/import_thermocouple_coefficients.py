"""Generate the offline Dart coefficients from the archived NIST reference file.
Source: https://its90.nist.gov/downloadFiles/allcoeff.tab.txt (retrieved 2026-11-12).
No inverse coefficients are imported: inverses are solved numerically.
"""
from pathlib import Path
import re
import json
ROOT = Path(__file__).resolve().parents[1]
text = (ROOT/'data/reference/nist_its90_coefficients.txt').read_text(errors='replace')
curves = {}
for block in text.split('name: reference function on ITS-90')[1:]:
    kind = re.search(r'type: ([BEJKNRST])', block)[1]
    lines=block.splitlines(); segments=[]
    for i,line in enumerate(lines):
        if not line.startswith('range:'): continue
        low,high,order=[v.strip() for v in line[6:].split(',')]
        coefficients=[float(v.strip()) for v in lines[i+1:i+2+int(order)]]
        assert len(coefficients)==int(order)+1
        exp = []
        if kind=='K' and float(low)==0:
            exp=[float(re.search(rf'a{n}\s*=\s*([\d.E+\-]+)',block)[1]) for n in range(3)]
        segments.append((low,high,coefficients,exp))
    assert segments
    curves[kind]=segments
assert set(curves)==set('BEJKNRST')
extra = json.loads((ROOT/'data/reference/bipm_thermocouples_ac.json').read_text())
for kind, segments in extra['curves'].items():
    curves[kind] = [(str(s['min']), str(s['max']), [c / 1000 for c in s['c']], []) for s in segments]
out=['// Generated by tool/import_thermocouple_coefficients.py from NIST SRD 60.',
     '// Source: https://its90.nist.gov/downloadFiles/allcoeff.tab.txt',
     '// A/C: BIPM Thermocouple Thermometry Part 1 (2025-12-19), Appendix A.',
     'typedef ThermocoupleSegment = ({double min, double max, List<double> c, List<double> a});',
     'const thermocoupleCurves = <String, List<ThermocoupleSegment>>{']
for kind,segments in curves.items():
    out.append(f"  '{kind}': [")
    for low,high,c,a in segments:
        out.append(f'    (min: {float(low)!r}, max: {float(high)!r}, c: {c!r}, a: {a!r}),')
    out.append('  ],')
out.append('};\n')
(ROOT/'lib/core/thermocouple_data.dart').write_text('\n'.join(out))
print('Imported',sum(len(s) for s in curves.values()),'polynomial segments for',','.join(curves))
